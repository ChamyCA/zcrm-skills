def _find_bundle() -> Path | None:
    for cand in (PKG_DIR / "executor_bundle", PKG_DIR.parents[1] / "executor" / "bundle"):
        if (cand / "cli.mjs").is_file() and (cand / "settings.fragment.json").is_file():
            return cand
    return None


def _node_warning() -> str | None:
    try:
        out = subprocess.run(["node", "--version"], capture_output=True, text=True, timeout=10).stdout
    except (OSError, subprocess.SubprocessError):
        return "Node.js was not found. The executor needs Node 20 or newer (https://nodejs.org)."
    m = re.match(r"v(\d+)", out.strip())
    if not m or int(m.group(1)) < 20:
        return f"Node.js {out.strip() or '(unknown version)'} found; the executor needs Node 20 or newer."
    return None


class MergeError(Exception):
    pass


def merge_json(user: object, frag: object, path: tuple = (), conflicts: list | None = None) -> object:
    """Merge frag into a copy of user. Never removes or overwrites user data.

    Dicts recurse; lists are unioned (order preserved, no duplicates); a differing user
    scalar wins, except protection scalars, which are recorded in `conflicts` and left alone.
    """
    conflicts = conflicts if conflicts is not None else []
    if isinstance(frag, dict):
        if not isinstance(user, dict):
            raise MergeError(f"{'.'.join(path) or '<root>'}: expected an object in your file")
        out = copy.deepcopy(user)
        for k, v in frag.items():
            if k not in out:
                out[k] = copy.deepcopy(v)
            elif path == ("hooks",) and k == "PreToolUse":
                out[k] = _merge_hooks(out[k], v)
            else:
                out[k] = merge_json(out[k], v, path + (k,), conflicts)
        return out
    if isinstance(frag, list):
        if not isinstance(user, list):
            raise MergeError(f"{'.'.join(path)}: expected a list in your file")
        out = copy.deepcopy(user)
        for item in frag:
            if item not in out:
                out.append(copy.deepcopy(item))
        return out
    if path in PROTECTIONS and user != frag:
        conflicts.append((path, user, frag))
    return user


def _hook_commands(entries: list) -> set[str]:
    cmds = set()
    for e in entries:
        if isinstance(e, dict):
            for h in e.get("hooks", []) or []:
                if isinstance(h, dict) and "command" in h:
                    cmds.add(h["command"])
    return cmds


def _merge_hooks(user: object, frag: list) -> list:
    if not isinstance(user, list):
        raise MergeError("hooks.PreToolUse: expected a list in your file")
    out = copy.deepcopy(user)
    have = _hook_commands(out)
    for entry in frag:
        if not (_hook_commands([entry]) & have):
            out.append(copy.deepcopy(entry))
            have |= _hook_commands([entry])
    return out


def _force_protections(obj: dict) -> None:
    for path, safe in PROTECTIONS.items():
        d = obj
        for k in path[:-1]:
            d = d.setdefault(k, {})
        d[path[-1]] = safe


def _diff_lines(old: object, new: object, path: str = "") -> list[str]:
    lines: list[str] = []
    if isinstance(new, dict):
        old = old if isinstance(old, dict) else {}
        for k, v in new.items():
            sub = f"{path}.{k}" if path else k
            if k not in old:
                lines.append(f"add {sub}")
            else:
                lines += _diff_lines(old[k], v, sub)
    elif isinstance(new, list):
        old = old if isinstance(old, list) else []
        for item in new:
            if item not in old:
                text = json.dumps(item) if not isinstance(item, str) else item
                lines.append(f"add to {path}: {text}")
    elif old != new:
        lines.append(f"set {path} = {new!r}")
    return lines


def _load_json_file(path: Path) -> tuple[dict | None, str | None]:
    """Returns (data or {} when missing, error message)."""
    if not path.exists():
        return {}, None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        return None, f"{path} is not valid JSON ({e}). Fix or remove it, then re-run. Nothing was written."
    if not isinstance(data, dict):
        return None, f"{path} must contain a JSON object. Nothing was written."
    return data, None


def _plan_gitignore(path: Path) -> str | None:
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    present = {ln.strip() for ln in existing.splitlines()}
    missing = [ln for ln in GITIGNORE_LINES if ln not in present]
    if not missing:
        return None
    sep = "" if (not existing or existing.endswith("\n")) else "\n"
    return existing + sep + "\n".join(missing) + "\n"


def _write_json_with_backup(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        backup = path.with_name(path.name + ".zcrm-backup")
        if not backup.exists():
            shutil.copyfile(path, backup)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def _install_executor(root: Path, bundle: Path, force: bool, dry_run: bool) -> int:
    """Returns the number of changes (planned in dry-run). Raises typer.Exit on conflict/invalid JSON.

    Everything that can fail (parsing, merging, conflicts) is checked before any file is written.
    """
    settings_path = root / ".claude" / "settings.json"
    mcp_path = root / ".mcp.json"
    plans = []  # (path, old, new, label)
    conflicts: list = []
    for path, frag_name in ((settings_path, "settings.fragment.json"), (mcp_path, "mcp.fragment.json")):
        user, err = _load_json_file(path)
        if err:
            console.print(f"[red]Error:[/red] {err}")
            raise typer.Exit(code=1)
        frag = json.loads((bundle / frag_name).read_text(encoding="utf-8"))
        try:
            merged = merge_json(user, frag, (), conflicts if path == settings_path else [])
        except MergeError as e:
            console.print(f"[red]Error:[/red] cannot merge into {path}: {e}. Nothing was written.")
            raise typer.Exit(code=1)
        plans.append((path, user, merged))

    if conflicts and not force:
        console.print("[red]Conflict:[/red] your .claude/settings.json weakens a required protection. It was NOT changed.")
        for cpath, have, want in conflicts:
            console.print(f"  - {'.'.join(cpath)} is {json.dumps(have)}; the executor requires {json.dumps(want)}")
        console.print(
            "Fix: edit .claude/settings.json and set the value(s) above, then re-run; "
            "or re-run with [bold]--force[/bold] to set the safe value(s) (a .zcrm-backup copy is kept). "
            "Nothing was installed."
        )
        raise typer.Exit(code=2)
    if conflicts:
        for _, user, merged in plans[:1]:
            _force_protections(merged)

    changes = 0
    tag = "would" if dry_run else "did"
    # executor files
    for name in EXEC_FILES:
        src, dest = bundle / name, root / EXEC_DIR / name
        if dest.exists() and dest.read_bytes() == src.read_bytes():
            continue
        changes += 1
        console.print(f"  {'[cyan]~[/cyan]' if dry_run else '[green]✓[/green]'} {tag} write {EXEC_DIR}/{name}")
        if not dry_run:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)
    run_dir = root / RUN_DIR_REL
    if not run_dir.is_dir():
        changes += 1
        console.print(f"  {'[cyan]~[/cyan]' if dry_run else '[green]✓[/green]'} {tag} create {RUN_DIR_REL}/")
        if not dry_run:
            run_dir.mkdir(parents=True, exist_ok=True)
    launcher = root / "zcrm-exec"
    if not launcher.exists() or launcher.read_text(encoding="utf-8") != LAUNCHER or not launcher.stat().st_mode & 0o100:
        changes += 1
        console.print(f"  {'[cyan]~[/cyan]' if dry_run else '[green]✓[/green]'} {tag} write ./zcrm-exec launcher")
        if not dry_run:
            launcher.write_text(LAUNCHER, encoding="utf-8")
            launcher.chmod(0o755)
    # merged json
    for path, user, merged in plans:
        if merged == user and path.exists():
            continue
        changes += 1
        rel = path.relative_to(root)
        console.print(f"  {'[cyan]~[/cyan]' if dry_run else '[green]✓[/green]'} {tag} {'update' if path.exists() else 'create'} {rel}")
        for ln in _diff_lines(user, merged):
            console.print(f"      {ln}")
        if not dry_run:
            _write_json_with_backup(path, merged)
    # .gitignore
    gi = root / ".gitignore"
    new_gi = _plan_gitignore(gi)
    if new_gi is not None:
        changes += 1
        console.print(f"  {'[cyan]~[/cyan]' if dry_run else '[green]✓[/green]'} {tag} append {' and '.join(GITIGNORE_LINES)} to .gitignore")
        if not dry_run:
            gi.write_text(new_gi, encoding="utf-8")
    return changes


