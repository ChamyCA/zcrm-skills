def _selected_skills(include_alignment: bool) -> list[dict]:
    return [k for k in SKILLS if include_alignment or not k.get("maintainer")]


def _copy_skills(
    target_skills_dir: Path, overwrite: bool, include_alignment: bool = False, dry_run: bool = False
) -> list[str]:
    installed = []
    if not dry_run:
        target_skills_dir.mkdir(parents=True, exist_ok=True)
    for skill in _selected_skills(include_alignment):
        src = SKILLS_SRC / skill["dir"]
        dest = target_skills_dir / skill["dir"]
        if dest.exists():
            if not overwrite:
                console.print(
                    f"  [yellow]skip[/yellow] {skill['dir']} already exists (use --force to overwrite)"
                )
                continue
            if not dry_run:
                shutil.rmtree(dest)
        if not dry_run:
            shutil.copytree(src, dest, ignore=shutil.ignore_patterns(".DS_Store", "__pycache__"))
        installed.append(skill["dir"])
    return installed


def _copy_docs(root: Path, overwrite: bool, dry_run: bool) -> list[str]:
    done = []
    for rel in SHIPPED_DOCS:
        src = DOCS_SRC / rel
        if not src.is_file():
            continue
        dest = root / rel
        if dest.exists():
            if dest.read_bytes() == src.read_bytes() or not overwrite:
                continue
        if not dry_run:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)
        done.append(rel)
    return done


GUIDE_NAME = "ZCRM-guide.html"


def _find_guide() -> Path | None:
    for cand in (PKG_DIR / "guide" / GUIDE_NAME, PKG_DIR.parents[1] / "docs" / "skills-help" / "index.html"):
        if cand.is_file():
            return cand
    return None


def _copy_guide(root: Path, overwrite: bool, dry_run: bool) -> bool:
    """Write <root>/ZCRM-guide.html. Returns True if written (or would be)."""
    src = _find_guide()
    if src is None:
        return False
    dest = root / GUIDE_NAME
    if dest.exists():
        if dest.read_bytes() == src.read_bytes():
            return False
        if not overwrite:
            console.print(f"  [yellow]![/yellow] {GUIDE_NAME} already exists; kept (use --force to replace)")
            return False
    if not dry_run:
        shutil.copyfile(src, dest)
    return True


