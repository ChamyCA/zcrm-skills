app = typer.Typer(
    name="zoho-skills",
    help="Install Zoho CRM pre-sales skills (CRM Data Model Customizer, Demo Pulse) into a project.",
    add_completion=False,
)


@app.command()
def init(
    project_name: str = typer.Argument(
        None, help="Name of the new project directory to create."
    ),
    here: bool = typer.Option(
        False, "--here", help="Install into the current directory instead of a new one."
    ),
    with_executor: bool = typer.Option(
        None,
        "--with-executor/--no-executor",
        help="Install the CRM Build Executor and its secret protections (default: on when a bundle is available).",
    ),
    include_alignment: bool = typer.Option(
        False, "--include-alignment", help="Also install the maintainer-only ZCRM-alignment skill."
    ),
    force: bool = typer.Option(
        False, "--force", help="Overwrite installed skills/docs and set safe values for conflicting protections."
    ),
    dry_run: bool = typer.Option(
        False, "--dry-run", help="Show exactly what would change; write nothing."
    ),
) -> None:
    """Create (or use) a project directory and install the skills (and the executor) into it."""
    _print_banner()

    if not here and not project_name:
        console.print("[red]Error:[/red] provide a project name, or pass --here to use the current directory.")
        raise typer.Exit(code=1)

    bundle = _find_bundle()
    if with_executor is True and bundle is None:
        console.print(
            "[red]Error:[/red] --with-executor was requested but no executor bundle is available. "
            "Run: [bold]cd executor && npm run bundle[/bold] (dev repo), or install a release wheel that includes it."
        )
        raise typer.Exit(code=1)
    install_executor = bundle is not None if with_executor is None else with_executor
    if with_executor is None and bundle is None:
        console.print("[yellow]Executor skipped:[/yellow] no executor bundle is available in this install.")

    if here:
        target_root = Path.cwd()
        project_name = target_root.name
    else:
        target_root = Path.cwd() / project_name
        if target_root.exists() and any(target_root.iterdir()):
            console.print(f"[red]Error:[/red] directory '{project_name}' already exists and is not empty.")
            raise typer.Exit(code=1)

    _print_setup_panel(project_name, Path.cwd(), target_root)
    if dry_run:
        console.print("[bold cyan]Dry run:[/bold cyan] nothing will be written.")
    console.print()

    changes = 0
    if install_executor:
        warn = _node_warning()
        if warn:
            console.print(f"[yellow]Warning:[/yellow] {warn} Skills still install; the executor will not run until Node 20+ is available.")
        # Preflight + executor merge runs first: conflicts or invalid JSON abort before anything is written.
        if not dry_run:
            target_root.mkdir(parents=True, exist_ok=True)
        changes += _install_executor(target_root, bundle, force, dry_run)  # type: ignore[arg-type]
    elif not dry_run:
        target_root.mkdir(parents=True, exist_ok=True)

    skills_dir = target_root / ".claude" / "skills"
    installed = _copy_skills(skills_dir, overwrite=force, include_alignment=include_alignment, dry_run=dry_run)
    for name in installed:
        console.print(f"  [green]✓[/green] {'would install' if dry_run else 'installed'} {name}")
    docs = _copy_docs(target_root, overwrite=force, dry_run=dry_run)
    for rel in docs:
        console.print(f"  [green]✓[/green] {'would write' if dry_run else 'wrote'} {rel}")
    guide = _copy_guide(target_root, overwrite=force, dry_run=dry_run)
    if guide:
        console.print(f"  [green]✓[/green] {'would write' if dry_run else 'wrote'} {GUIDE_NAME}")
    changes += len(installed) + len(docs) + (1 if guide else 0)
    console.print()

    if changes == 0:
        console.print("[bold green]Already up to date:[/bold green] nothing changed.")
        return
    if dry_run:
        console.print(f"[bold cyan]Dry run complete:[/bold cyan] {changes} change(s) would be made; nothing was written.")
        return
    _print_next_steps(project_name, is_here=here, executor=install_executor, include_alignment=include_alignment)


@app.command()
def check() -> None:
    """List the skills this toolkit installs, and whether the executor bundle is available."""
    _print_banner()
    for skill in SKILLS:
        kind = "maintainer, use --include-alignment" if skill.get("maintainer") else "default"
        console.print(f"  [cyan]{skill['command']}[/cyan] ({kind}) — {skill['label']}: {skill['blurb']}")
    bundle = _find_bundle()
    console.print()
    console.print(f"Executor bundle: {'available at ' + str(bundle) if bundle else 'not available'}")


def main() -> None:
    app()


if __name__ == "__main__":
    main()
